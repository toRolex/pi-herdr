import assert from 'node:assert/strict';
import { createJiti } from 'jiti';
import { randomUUID } from 'node:crypto';
const jiti = createJiti(import.meta.url);
const { makeDeliverySink } = await jiti.import('../src/push.ts');
const sessionA = `/tmp/pending-a-${randomUUID()}.jsonl`;
const sessionB = `/tmp/pending-b-${randomUUID()}.jsonl`;
let file = sessionA;
const sent = [], handlers = [];
const pi = { on: (_name, handler) => handlers.push(handler), sendMessage: (message, options) => sent.push({ message, options }) };
const confirmation = { getBranch: () => [], getSessionFile: () => file, timeoutMs: 0 };
const message = { content: 'normal final', details: { eventId: 'same-business-event' }, wake: true };
const first = makeDeliverySink(pi, confirmation);
assert.throws(() => first(message), /pending/);
assert.equal(sent.length, 1);
assert.equal(sent[0].options.deliverAs, 'steer');
const reload = makeDeliverySink(pi, confirmation);
for (const handler of handlers) handler({}, { sessionManager: { getBranch: () => [], getSessionFile: () => file } });
assert.throws(() => reload(message), /outcome unknown/);
assert.equal(sent.length, 1, 'normal reload retains unknown acknowledgement instead of re-enqueueing');
file = undefined;
assert.throws(() => reload(message), /outcome unknown/);
assert.equal(sent.length, 1, 'unknown session identity cannot prove SDK queue cleared');
file = sessionB;
for (const handler of handlers) handler({}, { sessionManager: { getBranch: () => [], getSessionFile: () => file } });
assert.throws(() => reload(message), /pending/);
assert.equal(sent.length, 2, 'a different session has an independent acknowledgement scope');
file = sessionA;
for (const handler of handlers) handler({}, { sessionManager: { getBranch: () => [], getSessionFile: () => file } });
assert.throws(() => reload(message), /outcome unknown/);
assert.equal(sent.length, 2, 'returning to the original session retains its unknown token');
console.log('delivery-pending-session: passed');

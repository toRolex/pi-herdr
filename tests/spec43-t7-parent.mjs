import assert from 'node:assert/strict';
import { createJiti } from 'jiti';
const jiti = createJiti(import.meta.url);
const { registerParentDelivery } = await jiti.import('../src/parent-delivery.ts');
const handlers = new Map();
const pi = { on(name, fn) { const h = handlers.get(name) ?? []; h.push(fn); handlers.set(name,h); return ()=>{}; } };
const dispatches=[];
const ctx={ sessionManager: { getSessionFile:()=>undefined } };
const parent=registerParentDelivery(pi, msg=>dispatches.push(msg), ()=> 'normal');
for(const h of handlers.get('agent_start') ?? []) await h({},ctx);
parent.accept({content:'late',details:{eventId:'event'},wake:true});
assert.equal(dispatches.length,0,'busy parent must not be interrupted');
for(const h of handlers.get('message_end') ?? []) await h({message:{role:'assistant',content:[{type:'text',text:'final'}]}},ctx);
for(const h of handlers.get('turn_end') ?? []) await h({message:{role:'assistant',content:[{type:'text',text:'final'}]},toolResults:[]},ctx);
assert.equal(dispatches.length,0,'closing boundary cannot start another turn');
for(const h of handlers.get('agent_settled') ?? []) await h({},ctx);
parent.accept({content:'finished-late',details:{eventId:'event2'},wake:true});
assert.equal(dispatches.length,0,'finished late completion stays unread');
for(const h of handlers.get('before_agent_start') ?? []) await h({},ctx);
assert.equal(dispatches.length,2,'next natural run consumes both deferred events');
assert.ok(dispatches.every(msg=>msg.deliverAs==='nextTurn'&&!msg.wake),'natural run never requests a new turn');
assert.equal(parent.allowCommit(dispatches[0].details),true,'fresh run safe boundary allows actual commit');
for(const h of handlers.get('message_end') ?? []) await h({message:{role:'assistant',content:[{type:'text',text:'final'}]}},ctx);
assert.equal(parent.allowCommit(dispatches[0].details),false,'submission rechecks closing boundary');
console.log('T7_PARENT_BUSY_CLOSING_FINISHED_NATURAL_PASS');

import assert from 'node:assert/strict';
import {createJiti} from 'jiti';
import {mkdtempSync,mkdirSync,readFileSync,writeFileSync,cpSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
for(const key of Object.keys(process.env))if(key.startsWith('HERDR_')||key.startsWith('PI_HERDR_')||key==='PI_SESSION_FILE')delete process.env[key];
const jiti=createJiti(import.meta.url);
const sdk=await jiti.import('../node_modules/@earendil-works/pi-coding-agent/dist/index.js');
const {registerQueueOnlyReceiver,enqueueQueueOnlyInbox,readQueueOnlyInbox}=await jiti.import('../src/queue-only-inbox.ts');
const provider=(await jiti.import('./fixtures/queue-only-demo.ts')).default;
const scratch=mkdtempSync(join(tmpdir(),'queue-sdk-demo-'));
const artifacts=resolve(process.argv[2]??'.agents/evidence/spec43-t4',`sdk-${Date.now()}`);mkdirSync(artifacts,{recursive:true});
process.env.QUEUE_DEMO_LOG=join(artifacts,'sdk-events.jsonl');
const settings=sdk.SettingsManager.inMemory({compaction:{enabled:false}});
const loader=new sdk.DefaultResourceLoader({cwd:scratch,agentDir:join(scratch,'agent'),settingsManager:settings,noExtensions:true,noSkills:true,noPromptTemplates:true,noThemes:true,noContextFiles:true,extensionFactories:[registerQueueOnlyReceiver,provider]});
await loader.reload();
const runtime=await sdk.ModelRuntime.create({authPath:join(scratch,'auth.json'),modelsPath:null,refreshOnCreate:false});
const model={provider:'queue-only-demo',id:'deterministic',name:'QueueOnly demo',api:'queue-only-demo-api',baseUrl:'http://localhost.invalid',reasoning:false,input:['text'],cost:{input:0,output:0,cacheRead:0,cacheWrite:0},contextWindow:128000,maxTokens:1024};
let session;
try{
 ({session}=await sdk.createAgentSession({cwd:scratch,agentDir:join(scratch,'agent'),resourceLoader:loader,modelRuntime:runtime,model,thinkingLevel:'off',settingsManager:settings,sessionManager:sdk.SessionManager.create(scratch,join(scratch,'sessions'))}));
 const events=()=>readFileSync(process.env.QUEUE_DEMO_LOG,'utf8').trim().split('\n').map(JSON.parse);
 const streams=()=>events().filter(e=>e.kind==='stream');
 const sp=session.sessionManager.getSessionFile();
 const busy=session.prompt('busy-start');
 while(streams().length<1)await new Promise(r=>setTimeout(r,20));
 const message=body=>({from:'sdk-sender',to:'sdk-receiver',body,text:body});
 assert(enqueueQueueOnlyInbox(sp,message('SDK_BUSY_PAYLOAD')).accepted);
 await busy;
 assert(session.sessionManager.getEntries().some(e=>e.message?.toolName==='bash'&&!e.message.isError&&JSON.stringify(e.message.content).includes('QUEUE_BUSY_TOOL_FINISHED')));
 assert(!JSON.stringify(streams()).includes('SDK_BUSY_PAYLOAD'));
 const before=streams().length;
 assert(enqueueQueueOnlyInbox(sp,message('SDK_IDLE_PAYLOAD')).accepted);
 await new Promise(r=>setTimeout(r,300));assert.equal(streams().length,before);
 assert.equal(readQueueOnlyInbox(sp).messages.length,2);
 await session.prompt('next-user-turn');
 assert.equal(streams().length,before+1);
 assert(JSON.stringify(streams().at(-1)).includes('SDK_BUSY_PAYLOAD')&&JSON.stringify(streams().at(-1)).includes('SDK_IDLE_PAYLOAD'));
 assert.equal(readQueueOnlyInbox(sp).messages.length,0,'settled reconciliation acknowledges only on-disk custom messages');
 cpSync(sp,join(artifacts,'sdk-session.jsonl'));
 writeFileSync(join(artifacts,'result.json'),JSON.stringify({exitCode:0,realAgentSession:true,busyToolContinues:true,idleNoModelCall:true,nextTurnConsumed:true,mailboxAcknowledged:true,streams:streams().length},null,2));
 console.log(`GREEN QueueOnly installed SDK ${artifacts}`);
}finally{session?.dispose();rmSync(scratch,{recursive:true,force:true});const dest=join('/tmp/spec43-notes/evidence/spec43-t4',artifacts.split('/').at(-1));mkdirSync(dest,{recursive:true});cpSync(artifacts,dest,{recursive:true});}
